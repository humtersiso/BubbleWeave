/** 相容舊匯出：預設第一組 */
export const PSYCH_QUESTIONS = PSYCH_QUIZ_SETS[0].questions;

export const PSYCH_SET_BY_ID = Object.fromEntries(PSYCH_QUIZ_SETS.map((s) => [s.id, s]));

export const pickPsychQuizSetId = () =>
  PSYCH_QUIZ_SETS[Math.floor(Math.random() * PSYCH_QUIZ_SETS.length)].id;

export const getPsychQuestions = (setId) =>
  PSYCH_SET_BY_ID[setId]?.questions || PSYCH_QUESTIONS;

/**
 * @param {Record<string, string>} answers qId → optionId
 * @param {object[]} [questions]
 * @returns {string[]}
 */
export const tagsFromQuizAnswers = (answers = {}, questions = PSYCH_QUESTIONS) => {
  const counts = new Map();
  for (const q of questions) {
    const optId = answers[q.id];
    const option = q.options.find((o) => o.id === optId);
    if (!option) continue;
    for (const tag of option.tags) {
      counts.set(tag, (counts.get(tag) || 0) + 1);
    }
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([tag]) => tag);
};
